/**
 * Bigram table over alphabet + boundary "^": entry (i, j) = round(-log2 P(j | i) * 4), capped at 61,
 * one base-62 digit per entry. Add-0.5 smoothing; trained on word types.
 */
function bigrams(words: string[], alphabet: string[]): string {
  const sym = ["^", ...alphabet];
  const idx = new Map(sym.map((c, i) => [c, i]));
  const n = sym.length;
  const counts = new Float64Array(n * n);
  for (const w of words) {
    let prev = 0;
    for (const ch of w) {
      const j = idx.get(ch);
      if (j === undefined) {
        prev = 0;
        continue;
      }
      counts[prev * n + j]! += 1;
      prev = j;
    }
    counts[prev * n + 0]! += 1;
  }
  const B62 = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ";
  let out = "";
  for (let i = 0; i < n; i++) {
    let row = 0;
    for (let j = 0; j < n; j++) row += counts[i * n + j]! + 0.5;
    for (let j = 0; j < n; j++) {
      const p = (counts[i * n + j]! + 0.5) / row;
      out += B62[Math.min(61, Math.round(-Math.log2(p) * 4))];
    }
  }
  return out;
}

write(
  "src/generated/bigrams.ts",
  HEADER +
    `// Thai: trained on all ${thaiAll.length} ICU words. English: on the English word list above.\n` +
    `// Row/column 0 is the word boundary; then the alphabet. Value = round(-log2 P(next | prev) * 4), base 62.\n` +
    `export const THAI_BIGRAM_ALPHABET = ${JSON.stringify(thaiAlphabet.join(""))};\n` +
    `export const THAI_BIGRAMS = ${JSON.stringify(bigrams(thaiAll, thaiAlphabet))};\n` +
    `export const ENGLISH_BIGRAM_ALPHABET = "abcdefghijklmnopqrstuvwxyz";\n` +
    `export const ENGLISH_BIGRAMS = ${JSON.stringify(bigrams(englishWords, [..."abcdefghijklmnopqrstuvwxyz"]))};\n`,
);
