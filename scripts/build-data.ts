// 2. Word lists
// ---------------------------------------------------------------------------

const SAFE: string[] = [];
for (let c = 0x21; c < 0x7f; c++) {
  const ch = String.fromCharCode(c);
  if (!"\\`$\"'".includes(ch)) SAFE.push(ch);
}

/**
 * Front-coded list: each word is <prefix-length symbol><rest of the word>, letters mapped to
 * single ASCII symbols so the module is plain ASCII. Decoder: src/wordlist.ts.
 */
function encodeList(words: string[], alphabet: string[]): { alphabet: string; data: string } {
  const sorted = [...new Set(words)].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  const maxPrefix = SAFE.length - alphabet.length - 1;
  if (maxPrefix < 8) throw new Error("alphabet too large");
  const enc = new Map(alphabet.map((c, i) => [c, SAFE[i]!]));
  let out = "";
  let prev = "";
  for (const w of sorted) {
    let p = 0;
    while (p < prev.length && p < w.length && prev[p] === w[p] && p < maxPrefix) p++;
    out += SAFE[alphabet.length + p];
    for (const ch of w.slice(p)) {
      const e = enc.get(ch);
      if (e === undefined) throw new Error(`char ${ch} not in alphabet (${w})`);
      out += e;
    }
    prev = w;
  }
  return { alphabet: alphabet.join(""), data: out };
}

const thaiAll = read("data/sources/icu-thaidict.txt")
  .replace(/^\uFEFF/, "")
  .split(/\r?\n/)
  .map((s) => s.trim())
  .filter((s) => s && !s.startsWith("#"));
const thaiSet = new Set(thaiAll);

/** True when w splits into two or more other dictionary words. */
function isCompound(w: string): boolean {
  const n = w.length;
  const reach = new Array<boolean>(n + 1).fill(false);
  reach[0] = true;
  for (let i = 0; i < n; i++) {
    if (!reach[i]) continue;
    for (let j = i + 2; j <= n; j++) {
      if (j - i === n) continue;
      if (thaiSet.has(w.slice(i, j))) reach[j] = true;
    }
  }
  return reach[n] === true;
}
const thaiKept = thaiAll.filter((w) => !isCompound(w));
const thaiAlphabet = [...new Set(thaiAll.join(""))].sort();
const thaiEnc = encodeList(thaiKept, thaiAlphabet);
write(
  "src/generated/thai-words.ts",
  HEADER +
    `// ${thaiKept.length} of ${thaiAll.length} words of ICU's thaidict.txt: the ones that are not two or more other words joined.\n` +
    `export const THAI_ALPHABET = ${JSON.stringify(thaiEnc.alphabet)};\n` +
    `export const THAI_WORDS = ${JSON.stringify(thaiEnc.data)};\n`,
);

const extra = read("data/extra-english.txt")
  .split(/\r?\n/)
  .map((s) => s.trim())
  .filter((s) => s && !s.startsWith("#"));
const esl = read("data/sources/12dicts-3esl.txt")
  .split(/\r?\n/)
  .map((s) => s.trim())
  .filter(Boolean);
// Single letters are not words here (except a and i): "c" or "z" alone is far more often the key
// of แ or ผ. Short all-capital abbreviations (GI, KO, TV …) are left out for the same reason; the
// few that matter in chats are in extra-english.txt. Words longer than 8 letters are left out to
// keep the bundle small: typed on the Thai layout they never look like Thai anyway (measured with
// scripts/eval.ts: same results with and without them).
const englishWords = [
  ...esl.filter((w) => /^[a-z]+$/.test(w) && w.length <= 8 && (w.length > 1 || w === "a" || w === "i")),
  // one-word proper nouns of 3esl (America, April, Bangkok …), lowercased
  ...esl.filter((w) => /^[A-Z][a-z]+$/.test(w)).map((w) => w.toLowerCase()),
  // longer acronyms (AIDS, NASA …)
  ...esl.filter((w) => /^[A-Z]{4,}$/.test(w)).map((w) => w.toLowerCase()),
  ...extra.filter((w) => /^[a-z0-9]+$/.test(w)),
];
const englishAlphabet = [..."abcdefghijklmnopqrstuvwxyz0123456789"];
const englishEnc = encodeList(englishWords, englishAlphabet);
write(
  "src/generated/english-words.ts",
  HEADER +
    `// 12dicts 3esl (public domain) one-word entries of at most 8 letters + data/extra-english.txt: ${new Set(englishWords).size} words.\n` +
    `export const ENGLISH_ALPHABET = ${JSON.stringify(englishEnc.alphabet)};\n` +
    `export const ENGLISH_WORDS = ${JSON.stringify(englishEnc.data)};\n`,
);

