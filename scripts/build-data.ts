/**
 * Builds src/generated/*.ts from the sources in data/.
 *
 *   npm run data
 *
 * Inputs (see NOTICE.md for licences):
 *   data/sources/cldr/*.xml            Unicode CLDR release-40 keyboard files (Unicode License v3)
 *   data/sources/macos/*.tsv           what macOS 27 itself types, dumped by scripts/layouts/macos-dump.swift
 *   data/sources/icu-thaidict.txt      ICU 76.1 Thai word-break dictionary (Unicode License v3)
 *   data/sources/12dicts-3esl.txt      12dicts "3esl" core English list by Alan Beale (public domain)
 *   data/extra-english.txt             tech / chat words written for this project
 *
 * Outputs:
 *   src/generated/layout-data.ts       key → character tables for the four layouts
 *   src/generated/thai-words.ts        compact Thai word list (compounds dropped, front-coded)
 *   src/generated/english-words.ts     compact English word list (front-coded)
 *   src/generated/bigrams.ts           Thai and English character bigram tables
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p: string) => readFileSync(join(root, p), "utf8");
const write = (p: string, s: string) => {
  writeFileSync(join(root, p), s);
  console.log(`wrote ${p} (${Buffer.byteLength(s)} bytes)`);
};
const HEADER = "// GENERATED by scripts/build-data.ts — do not edit by hand. Sources: see NOTICE.md.\n";

// ---------------------------------------------------------------------------
// 1. Layouts
// ---------------------------------------------------------------------------

/** ISO key position → [unshifted, shifted] character on a US QWERTY keyboard. */
const US: Record<string, [string, string]> = {
  E00: ["`", "~"], E01: ["1", "!"], E02: ["2", "@"], E03: ["3", "#"], E04: ["4", "$"], E05: ["5", "%"],
  E06: ["6", "^"], E07: ["7", "&"], E08: ["8", "*"], E09: ["9", "("], E10: ["0", ")"], E11: ["-", "_"], E12: ["=", "+"],
  D01: ["q", "Q"], D02: ["w", "W"], D03: ["e", "E"], D04: ["r", "R"], D05: ["t", "T"], D06: ["y", "Y"],
  D07: ["u", "U"], D08: ["i", "I"], D09: ["o", "O"], D10: ["p", "P"], D11: ["[", "{"], D12: ["]", "}"],
  // The US backslash key: CLDR's macOS files call it D13, its Windows files C12 (scan code 0x2B).
  D13: ["\\", "|"], C12: ["\\", "|"],
  C01: ["a", "A"], C02: ["s", "S"], C03: ["d", "D"], C04: ["f", "F"], C05: ["g", "G"], C06: ["h", "H"],
  C07: ["j", "J"], C08: ["k", "K"], C09: ["l", "L"], C10: [";", ":"], C11: ["'", '"'],
  B01: ["z", "Z"], B02: ["x", "X"], B03: ["c", "C"], B04: ["v", "V"], B05: ["b", "B"], B06: ["n", "N"],
  B07: ["m", "M"], B08: [",", "<"], B09: [".", ">"], B10: ["/", "?"],
};

function unescapeXml(s: string): string {
  return s
    .replace(/\\u\{([0-9A-Fa-f]+)\}/g, (_, h: string) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"');
}

function cldrKeyMaps(xml: string): Map<string, Map<string, string>> {
  const out = new Map<string, Map<string, string>>();
  for (const m of xml.matchAll(/<keyMap(?: modifiers="([^"]*)")?>([\s\S]*?)<\/keyMap>/g)) {
    const map = new Map<string, string>();
    for (const k of (m[2] ?? "").matchAll(/<map iso="(\w+)" to="([^"]*)"/g)) map.set(k[1]!, unescapeXml(k[2]!));
    out.set(m[1] ?? "", map);
  }
  return out;
}

type Pairs = Array<[key: string, char: string]>;

function fromCldr(file: string, shiftModifier: string): Pairs {
  const maps = cldrKeyMaps(read(`data/sources/cldr/${file}`));
  const base = maps.get("");
  const shift = maps.get(shiftModifier);
  if (!base || !shift) throw new Error(`${file}: keyMap missing`);
  const pairs: Pairs = [];
  for (const [iso, [plain, shifted]] of Object.entries(US)) {
    const b = base.get(iso);
    const s = shift.get(iso);
    if (b !== undefined) pairs.push([plain, b]);
    if (s !== undefined) pairs.push([shifted, s]);
  }
  return pairs;
}

/** Reads the TSV written by scripts/layouts/macos-dump.swift (key, base, shifted key, left-shift, right-shift). */
function fromMacDump(id: string): Pairs {
  const lines = read("data/sources/macos/macos-27-thai-layouts.tsv").split("\n");
  const pairs: Pairs = [];
  let on = false;
  for (const line of lines) {
    if (line.startsWith("== ")) {
      on = line.slice(3).trim() === id;
      continue;
    }
    if (!on || !line) continue;
    const [k, b, sk, ls] = line.split("\t");
    if (k === undefined || b === undefined || sk === undefined || ls === undefined) continue;
    if (b !== "") pairs.push([k, b]);
    if (ls !== "") pairs.push([sk, ls]);
  }
  if (!pairs.length) throw new Error(`no macOS dump for ${id}`);
  return pairs;
}

const usable = (c: string) => c !== " " && c !== "\u200b" && !/[\uE000-\uF8FF]/.test(c) && [...c].length === 1;

const layouts: Record<string, Pairs> = {
  kedmanee: fromCldr("th-t-k0-windows.xml", "shift caps"),
  "kedmanee-mac": fromCldr("th-t-k0-osx.xml", "shiftL"),
  pattachote: fromCldr("th-t-k0-windows-patta.xml", "shift caps"),
  // CLDR's macOS Pattachote (2014 data) has "}" → ภ; macOS 27 types ฦ there, so the OS dump wins.
  "pattachote-mac": fromMacDump("com.apple.keylayout.Thai-PattaChote"),
};

// Cross-check: CLDR's macOS Kedmanee must equal what macOS 27 types (left shift).
{
  const a = new Map(layouts["kedmanee-mac"]);
  const b = new Map(fromMacDump("com.apple.keylayout.Thai"));
  for (const [k, v] of b) if (a.get(k) !== v) throw new Error(`kedmanee-mac: CLDR ${a.get(k)} vs macOS ${v} on ${k}`);
  for (const [k, v] of a) if (b.get(k) !== v) throw new Error(`kedmanee-mac: CLDR ${v} vs macOS ${b.get(k)} on ${k}`);
}

let layoutTs = HEADER;
layoutTs += `/** Per layout: KEYS[i] (what a US keyboard types) ↔ CHARS[i] (what the Thai layout types on that key). */\n`;
layoutTs += `export const LAYOUT_DATA = {\n`;
for (const [name, pairs] of Object.entries(layouts)) {
  const ok = pairs.filter(([k, c]) => usable(c) && k.length === 1);
  const keys = ok.map(([k]) => k).join("");
  const chars = ok.map(([, c]) => c).join("");
  layoutTs += `  ${JSON.stringify(name)}: { keys: ${JSON.stringify(keys)}, chars: ${JSON.stringify(chars)} },\n`;
}
layoutTs += `} as const;\n`;
write("src/generated/layout-data.ts", layoutTs);

